// Generates src/data/wend-words.ts: the English word list used by the Wend solver.
// Usage: node scripts/make-wend-dict.mjs   (or npm run dict:wend)
//
// Sources (devDependencies, both permissively licensed):
//   - wordlist-english (SCOWL, Kevin Atkinson; MIT-like SCOWL licence). SCOWL sorts
//     words into size levels 10, 20, 35, 40, 50, 55, 60, 70; a lower level means a
//     more common word. These levels are the commonness rank (0..7).
//   - an-array-of-english-words (MIT, Letterpress word list). Words it has that are
//     not in SCOWL <= 70 get the lowest rank (8).
// Kept: lowercase a-z only, 3..12 letters. Stored upper-cased at load time.
//
// Format of the packed string: one block per rank (0..8), separated by '\n'.
// In a block the words are sorted; each is written as one header char
// String.fromCharCode(48 + k) (k = letters shared with the previous word of the
// block, 0..11) followed by the remaining letters. Decoder: src/data/wend-dict.ts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const ok = (w) => /^[a-z]{3,12}$/.test(w);

const scowlDir = dirname(require.resolve('wordlist-english/package.json'));
const levels = [10, 20, 35, 40, 50, 55, 60, 70];
const dialects = ['english', 'american', 'british', 'canadian', 'australian'];
const rank = new Map();
levels.forEach((lvl, r) => {
  for (const d of dialects) {
    const words = JSON.parse(readFileSync(join(scowlDir, `${d}-words-${lvl}.json`), 'utf8'));
    for (const w of words) if (ok(w) && !rank.has(w)) rank.set(w, r);
  }
});
const extraRank = levels.length;
for (const w of require('an-array-of-english-words')) if (ok(w) && !rank.has(w)) rank.set(w, extraRank);

const blocks = Array.from({ length: extraRank + 1 }, () => []);
for (const [w, r] of rank) blocks[r].push(w);
const packed = blocks.map((ws) => {
  ws.sort();
  let prev = '', out = '';
  for (const w of ws) {
    let k = 0;
    while (k < prev.length && k < w.length && prev[k] === w[k]) k++;
    out += String.fromCharCode(48 + k) + w.slice(k);
    prev = w;
  }
  return out;
}).join('\n');

const out = 'src/data/wend-words.ts';
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out,
  '// GENERATED by scripts/make-wend-dict.mjs; do not edit.\n' +
  '// Words from SCOWL via wordlist-english (Copyright 2000-2016 Kevin Atkinson, SCOWL licence,\n' +
  '// permissive) and an-array-of-english-words (MIT, Zeke Sikelianos). See the README (Wend).\n' +
  `// ${rank.size} words, ${blocks.length} rank blocks; format described in the generator.\n` +
  `export const WEND_WORDS_PACKED = ${JSON.stringify(packed)};\n`);
console.log(`${out}: ${rank.size} words, ${(packed.length / 1024).toFixed(0)} KB ` +
  `(per rank: ${blocks.map((b) => b.length).join(', ')})`);
